#!/usr/bin/env python3
"""Plot Role B's jammer sanity sweep from results/pdr-sweep.csv.

Input columns: jammer_mode,jammer_power_dbm,distance_m,tx,rx
The script writes pdr-vs-power.png and pdr-vs-distance.png.
"""
import argparse
import csv
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt


def read_rows(path):
    groups = defaultdict(list)
    with path.open(newline="") as source:
        for row in csv.DictReader(source):
            tx, rx = int(row["tx"]), int(row["rx"])
            if tx:
                groups[row["jammer_mode"]].append(
                    (float(row["jammer_power_dbm"]), float(row["distance_m"]), rx / tx)
                )
    return groups


def plot(groups, index, xlabel, output):
    plt.figure(figsize=(6.4, 4.2))
    for mode, values in sorted(groups.items()):
        buckets = defaultdict(list)
        for value in values:
            buckets[value[index]].append(value[2])
        xs = sorted(buckets)
        ys = [sum(buckets[x]) / len(buckets[x]) for x in xs]
        plt.plot(xs, ys, marker="o", label=mode)
    plt.xlabel(xlabel)
    plt.ylabel("Packet delivery ratio")
    plt.ylim(-0.02, 1.02)
    plt.grid(alpha=0.3)
    plt.legend(title="Jammer")
    plt.tight_layout()
    plt.savefig(output, dpi=180)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path, help="CSV generated by scripts/run-pdr-sweep.sh")
    parser.add_argument("--out-dir", type=Path, default=Path("results"))
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    groups = read_rows(args.input)
    if not groups:
        raise SystemExit("No valid sweep rows found (tx must be non-zero).")
    plot(groups, 0, "Jammer transmit power (dBm)", args.out_dir / "pdr-vs-power.png")
    plot(groups, 1, "Jammer distance from receiver (m)", args.out_dir / "pdr-vs-distance.png")


if __name__ == "__main__":
    main()
